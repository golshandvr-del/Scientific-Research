import type { Candle } from '../indicators'

/** نسخهٔ قرارداد — هر تغییرِ ناسازگار باید این را بالا ببرد و adapter بنویسد. */
export const PRICE_FEED_VERSION = 1 as const

/**
 * PriceFeed@v1 — خروجیِ استانداردِ گرهِ قیمت برای یک (asset, tf).
 * تنها منبعِ حقیقتِ قیمت که گره‌های اندیکاتور/بستر مصرف می‌کنند.
 */
export interface PriceFeed {
  /** نسخهٔ قرارداد (همیشه === PRICE_FEED_VERSION در v1). */
  v: typeof PRICE_FEED_VERSION
  asset: string
  tf: string
  /** قیمتِ زندهٔ لحظه‌ای (spot/merged) روی مقیاسِ نمایش. */
  livePrice: number
  /** سنِ قیمتِ زنده بر حسبِ ثانیه (برای Heartbeat — ایدهٔ #۷). */
  liveAgeSec: number
  /** منبعِ دادهٔ زنده که واقعاً استفاده شد (مثلِ 'yahoo:GC=F' یا 'spot'). */
  source: string
  /** کندل‌ها روی مقیاسِ نمایش (rebased به spot در موردِ طلا). */
  candles: Candle[]
  /** کندل‌های «فقط-بسته‌شده» برای منطقِ تصمیم/ماشه (معادلِ shift(1)). */
  closed: Candle[]
  /** زمانِ آخرین کندلِ بسته‌شده. */
  lastClosedTime: number
}

/** وضعیتِ سلامتِ گرهِ قیمت — پایهٔ Heartbeat (ایدهٔ #۷). */
export interface PriceHealth {
  ok: boolean
  liveAgeSec: number
  stale: boolean            // liveAgeSec > آستانه (پیش‌فرض ۹۰ ثانیه)
  source: string
  note?: string
}

/** آستانهٔ کهنگیِ قیمت (ثانیه) که فراتر از آن Heartbeat هشدار می‌دهد. */
export const STALE_THRESHOLD_SEC = 90
