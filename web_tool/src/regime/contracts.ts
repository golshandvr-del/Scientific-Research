// گره ۵ در webplan §۳. رادارِ رژیم یک گرهِ مستقل است که از IndicatorSnapshot تصمیم
// می‌گیرد بازار در کدام «رژیم» است (روند/رنج/نوسان/آرام) و کدام *نوعِ* لایه اجازهٔ
// روشن‌شدن دارد. این پیاده‌سازیِ معماریِ «قانونِ شاید هیچ‌چیز ثابت نیست» است:
// لایهٔ سوخته شاید فقط «در رژیمِ درستش» زنده باشد.
//
// ⚠️ P3.5 «سایه‌ای/گزارش‌گر» است: این گره فقط رژیم را *گزارش* می‌کند. هنوز هیچ لایه‌ای
//    را خاموش نمی‌کند و مسیرِ /api/decision را تغییر نمی‌دهد (برابریِ بیت‌به‌بیت).
//    فعال‌سازیِ enabledKinds به فازهای بعد (Council/Runtime) موکول است.
// ============================================================================

/** نسخهٔ قرارداد — تغییرِ ناسازگار ⇒ v2 + adapter. */
export const REGIME_INFO_VERSION = 1 as const

/** پنج رژیمِ بازار (طبقِ webplan §۳ گره ۵). */
export type Regime = 'TREND_UP' | 'TREND_DOWN' | 'RANGE' | 'VOLATILE' | 'QUIET'

/**
 * انواعِ لایه (kind) که رادار می‌تواند روشن/خاموش کند. این‌ها برچسبِ *سبکِ* لایه‌اند،
 * نه شمارهٔ استراتژی. یک لایه در رجیستری می‌تواند kind خود را اعلام کند.
 *   - trend  : دنبال‌کنندهٔ روند (فقط در روند فعال)
 *   - fade   : بازگشت‌به‌میانگین/محو (فقط در رنج فعال)
 *   - breakout: شکست (در نوسانِ رونددار فعال)
 *   - neutral: مستقل از رژیم (همیشه مجاز)
 */
export type LayerKind = 'trend' | 'fade' | 'breakout' | 'neutral'

/** خروجیِ ثابتِ رادارِ رژیم (RegimeInfo@v1). */
export interface RegimeInfo {
  /** نسخهٔ قرارداد. */
  readonly v: typeof REGIME_INFO_VERSION
  /** رژیمِ تشخیص‌داده‌شده. */
  readonly regime: Regime
  /** شدتِ اطمینان به رژیم در بازهٔ 0..1. */
  readonly strength: number
  /** توضیحِ کوتاهِ فارسیِ دلیلِ تشخیص (برای گزارش/مستندات، نه لزوماً UI). */
  readonly note: string
  /** کدام نوعِ لایه اجازهٔ روشن‌شدن دارد (در فازِ سایه‌ای فقط گزارش می‌شود). */
  readonly enabledKinds: LayerKind[]
  // --- شاخص‌های خامِ تصمیم (برای شفافیت و کاوشگرِ P8) ---
  readonly adx: number
  readonly atrPct: number
  readonly emaSlopePct: number
  readonly bbWidthPct: number
}
