export interface S1516Features {
  priorMinLow: number[]   // max(low[i−L .. i−1]) — سدِ کف، علّی (shift 1)
  ff: boolean[]           // حالت: low[i] > priorMinLow[i]
  fresh: boolean[]        // لبهٔ تازه: ff ∧ ¬ff[i−1]   (دامِ ③)
  drift: boolean[]        // گیتِ علّی: close[i−1] − close[i−L] > 0  (دامِ ④)
  sig: boolean[]          // fresh ∧ drift
}

/**
 * پورتِ عینِ `strategies/s1516_cal_floor.py` — همه علّی، هیچ look-ahead.
 *
 *   ff_state:   low > low.rolling(L).max().shift(1)
 *   sig_fresh:  ff & ~ff.shift(1, fill_value=False) & drift_mask
 *   drift_mask: (close.shift(1) − close.shift(L)) > 0
 *
 * ⚠️ توجه به دامِ ②: سدِ کف با **max روی low** ساخته می‌شود (بالاترین کفِ
 *    L کندلِ گذشته)، و مقایسه با **low** کندلِ جاری است — نه close. یعنی
 *    «کلِ کندل بالای همهٔ کف‌های اخیر»، که تعریفِ «هوای پاک» در S1511 است.
 */
export function s1516Features(candles: Candle[], cfg: S1516Config): S1516Features {
  const n = candles.length
  const L = cfg.lookback

  const priorMinLow = new Array<number>(n).fill(NaN)
  // rolling(L).max().shift(1) ⇒ نخستین مقدارِ معتبر در i = L است.
  for (let i = L; i < n; i++) {
    let m = -Infinity
    for (let j = i - L; j <= i - 1; j++) if (candles[j].low > m) m = candles[j].low
    priorMinLow[i] = m
  }

  const ff = new Array<boolean>(n).fill(false)
  for (let i = 0; i < n; i++) {
    // NaN ⇒ false (عینِ .fillna(False) در `_b()` رانر)
    ff[i] = isFinite(priorMinLow[i]) && candles[i].low > priorMinLow[i]
  }

  // گیتِ درفتِ علّی — دامِ ④: از close[i−1] و close[i−L]، هرگز close[i].
  const drift = new Array<boolean>(n).fill(false)
  for (let i = L; i < n; i++) {
    drift[i] = candles[i - 1].close - candles[i - L].close > 0
  }

  const fresh = new Array<boolean>(n).fill(false)
  const sig = new Array<boolean>(n).fill(false)
  for (let i = 0; i < n; i++) {
    fresh[i] = ff[i] && !(i > 0 ? ff[i - 1] : false)
    sig[i] = fresh[i] && drift[i]
  }

  return { priorMinLow, ff, fresh, drift, sig }
}

export function computeS1516(candles: Candle[], cfg: S1516Config): RawSignal {
  const n = candles.length
  const L = cfg.lookback
  // کفِ داده: سدِ کف به L کندل و گیتِ درفت هم به L کندل نیاز دارد؛ یک کندل
  // اضافه برای مقایسهٔ لبهٔ تازه (ff[i−1]). صادقانه گزارش می‌شود، نه سیگنالِ الکی.
  const minBars = L + 2

  const pipSize = 0.01   // XAUUSD — عینِ pip_size() هارنس
  const slDist = cfg.slPip * pipSize
  const tpDist = cfg.tpPip * pipSize

  const baseInd: RouterDecision['indicators'] = []

  if (n < minBars) {
    return {
      active: false, approaching: false, direction: 'LONG',
      slDist, tpDist, maxHoldBars: cfg.maxHold,
      reason:
        `دادهٔ ناکافی: این لایه دستِ‌کم ${minBars} کندلِ ${cfg.tfFa} می‌خواهد ` +
        `(سدِ کفِ ${L}-کندلی + گیتِ درفتِ ${L}-کندلی + یک کندل برای تشخیصِ لبهٔ تازه)، ` +
        `ولی فیدِ فعلی ${n} کندل دارد ⇒ هیچ حکمی صادر نمی‌شود.`,
      indicators: baseInd,
    }
  }

  const f = s1516Features(candles, cfg)
  const i = n - 1
  const last = candles[i]
  const barrier = f.priorMinLow[i]
  const gapPct = isFinite(barrier) ? ((last.low - barrier) / barrier) * 100 : NaN

  const ind: RouterDecision['indicators'] = [
    { name: `سدِ کف (بالاترین کفِ ${L} کندلِ اخیر)`,
      value: isFinite(barrier) ? barrier.toFixed(2) : '—',
      ok: isFinite(barrier) },
    { name: 'کفِ کندلِ جاری',
      value: last.low.toFixed(2),
      ok: f.ff[i] },
    { name: 'فاصله تا سد',
      value: isFinite(gapPct) ? `${gapPct >= 0 ? '+' : ''}${gapPct.toFixed(2)}٪` : '—',
      ok: f.ff[i] },
    { name: 'لبهٔ تازه (کندلِ قبل رکورد نبوده)',
      value: f.fresh[i] ? 'بله' : 'خیر',
      ok: f.fresh[i] },
    { name: `گیتِ درفتِ علّی (close[−1] > close[−${L}])`,
      value: f.drift[i] ? 'مثبت' : 'منفی',
      ok: f.drift[i] },
  ]

  // ── وضعیتِ ENTRY ─────────────────────────────────────────────────────────
  if (f.sig[i]) {
    return {
      active: true, approaching: false, direction: 'LONG',
      slDist, tpDist, maxHoldBars: cfg.maxHold,
      reason:
        `کفِ تازهٔ تقویم‌همتا روی ${cfg.tfFa}: کفِ این کندل (${last.low.toFixed(2)}) ` +
        `بالاتر از **همهٔ** کف‌های ${L} کندلِ گذشته (=۳۰ روزِ معاملاتی، سد ` +
        `${barrier.toFixed(2)}) است و کندلِ قبل چنین نبود ⇒ لبهٔ تازه. ` +
        `گیتِ درفتِ علّی هم مثبت است. معنای اقتصادی: **غیابِ عرضه** — در ` +
        `محدوده‌ای که یک ماه فروشنده داشت، دیگر فروشنده‌ای پایین نمی‌کشد.`,
      indicators: ind,
    }
  }

  // ── وضعیتِ APPROACHING ───────────────────────────────────────────────────
  // نزدیکِ سد ولی هنوز بالایش نرفته، **و** گیتِ درفت مثبت است.
  const nearBarrier = isFinite(barrier)
    && last.low >= barrier * cfg.approachFrac
    && !f.ff[i]
  if (nearBarrier && f.drift[i]) {
    return {
      active: false, approaching: true, direction: 'LONG',
      slDist, tpDist, maxHoldBars: cfg.maxHold,
      reason:
        `نزدیکِ کفِ تازه روی ${cfg.tfFa}: کفِ کندل (${last.low.toFixed(2)}) تا سدِ ` +
        `${L}-کندلی (${barrier.toFixed(2)}) فقط ${Math.abs(gapPct).toFixed(2)}٪ فاصله دارد ` +
        `و گیتِ درفت مثبت است — ولی هنوز **بالای** سد نیست.`,
      approachReason:
        `تأییدِ لازم: کفِ کندل باید از ${barrier.toFixed(2)} بالاتر برود ` +
        `(کلِ کندل در هوای پاک). تا آن لحظه ورود نداریم.`,
      indicators: ind,
    }
  }

  // ── وضعیتِ NEUTRAL ───────────────────────────────────────────────────────
  let why: string
  if (f.ff[i] && !f.fresh[i]) {
    why = `کفِ کندل بالای سد هست، ولی کندلِ قبل هم چنین بود ⇒ **لبهٔ تازه نیست** `
      + `(این لایه رویداد می‌خرد نه حالت؛ وگرنه یک روندِ صعودی ده‌ها سیگنالِ تکراری می‌داد).`
  } else if (f.fresh[i] && !f.drift[i]) {
    why = `لبهٔ کفِ تازه هست، ولی **گیتِ درفتِ علّی منفی** است `
      + `(close[−1] پایین‌تر از close[−${L}]) ⇒ خارج از فضایی که حکم در آن صادر شد.`
  } else if (isFinite(barrier)) {
    why = `کفِ کندل (${last.low.toFixed(2)}) زیرِ سدِ ${L}-کندلی (${barrier.toFixed(2)}) است `
      + `⇒ هنوز در محدودهٔ کف‌های یک ماهِ گذشته‌ایم.`
  } else {
    why = 'سدِ کف هنوز تعریف نشده (گرم‌شدنِ پنجره).'
  }

  return {
    active: false, approaching: false, direction: 'LONG',
    slDist, tpDist, maxHoldBars: cfg.maxHold,
    reason: `بدونِ سیگنال روی ${cfg.tfFa}. ${why}`,
    indicators: ind,
  }
}

