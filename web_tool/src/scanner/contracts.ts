/** نسخهٔ قراردادِ کاوشگر — هر تغییرِ ناسازگار این عدد را بالا می‌برد و adapter می‌خواهد. */
export const SCAN_REPORT_VERSION = 1 as const

/** جهتِ لبهٔ کشف‌شده: آیا بالا بودنِ اندیکاتور، حرکتِ صعودی را پیش‌بینی می‌کند یا نزولی؟ */
export type EdgeDirection = 'BULLISH' | 'BEARISH' | 'NEUTRAL'

// ----------------------------------------------------------------------------
// IndicatorEdge@v1 — نتیجهٔ کاوشِ یک اندیکاتور روی یک (asset,tf).
// ----------------------------------------------------------------------------
export interface IndicatorEdge {
  /** نامِ اندیکاتورِ رجیستری‌شده (مثلاً 'rsi', 'adx', 'alligator'). */
  readonly indicator: string
  /** زیرسری (برای اندیکاتورهای چند-سری مثل adx.adx یا macd.hist)؛ برای تک-سری تهی. */
  readonly sub?: string
  /** پارامترهای به‌کاررفته (کلیدِ بازتولید). */
  readonly params: Record<string, number>

  // --- سنجه‌های آماریِ لبه (روی نمونهٔ درون-نمونه‌ایِ تاریخچه) ---
  /**
   * همبستگیِ اسپیرمن (رتبه‌ای) بینِ مقدارِ اندیکاتور در بارِ t و بازدهِ آیندهٔ بار t→t+horizon.
   * بازهٔ [-1..+1]. علامتِ آن جهتِ خامِ لبه را می‌دهد؛ اسپیرمن به outlier مقاوم‌تر از پیرسون است.
   */
  readonly spearman: number
  /** آزمونِ معناداری: |r|·sqrt(n-2)/sqrt(1-r²) → t-stat؛ p تقریبیِ دو-دامنه. */
  readonly pValue: number
  /** تعدادِ جفتِ (اندیکاتور، بازدهِ آینده) که در محاسبه استفاده شد. */
  readonly n: number

  // --- سنجهٔ «فیلترِ احیا»: تفاوتِ میانگینِ بازدهِ آینده بینِ صدکِ بالا و پایینِ اندیکاتور ---
  /** میانگینِ بازدهِ آیندهٔ بارهایی که اندیکاتورشان در صدکِ بالا (≥ topPct) است — به ٪. */
  readonly topBucketRet: number
  /** میانگینِ بازدهِ آیندهٔ بارهایی که اندیکاتورشان در صدکِ پایین (≤ botPct) است — به ٪. */
  readonly botBucketRet: number
  /** فاصلهٔ صدکِ بالا و پایین (topBucketRet − botBucketRet) — «قدرتِ تفکیکِ» فیلتر، به ٪. */
  readonly spread: number

  /** جهتِ لبه پس از داوریِ معناداری. */
  readonly direction: EdgeDirection
  /** آیا این اندیکاتور «کاندیدِ فیلترِ احیا» است؟ (p<0.05 و |spread| معنادار) */
  readonly isCandidate: boolean
}

// ----------------------------------------------------------------------------
// ScanReport@v1 — خروجیِ استانداردِ گرهِ کاوشگر برای یک (asset,tf,horizon).
// ----------------------------------------------------------------------------
export interface ScanReport {
  readonly v: typeof SCAN_REPORT_VERSION
  readonly asset: string
  readonly tf: string
  /** افقِ پیش‌بینی: بازدهِ بار t تا t+horizon (چند کندل جلوتر). */
  readonly horizon: number
  /** تعدادِ کندلِ ورودیِ استفاده‌شده در کاوش. */
  readonly barCount: number
  /** زمانِ ساختِ گزارش (ms). */
  readonly generatedAt: number
  /**
   * لیستِ لبه‌ها، مرتب‌شده نزولی بر اساسِ |spread|×معناداری (قوی‌ترین کاندیدِ فیلتر بالا).
   */
  readonly edges: IndicatorEdge[]
  /** کاندیداهای فیلترِ احیا (زیرمجموعهٔ edges با isCandidate=true) — خلاصهٔ سریعِ AI. */
  readonly candidates: IndicatorEdge[]
  /** توضیحِ فارسیِ خلاصهٔ نتیجه (برای گزارشِ تحقیق). */
  readonly note: string
}

/** آستانهٔ معناداریِ آماری برای «کاندیدِ فیلترِ احیا». */
export const SCAN_P_THRESHOLD = 0.05 as const
/** کفِ نمونه برای اعتبارِ کاوش (کمتر از این = داده ناکافی). */
export const SCAN_MIN_SAMPLES = 200 as const
/** حداقلِ |spread| (٪) تا یک لبه ارزشِ «کاندیدِ فیلتر» داشته باشد. */
export const SCAN_MIN_SPREAD_PCT = 0.03 as const
/** صدکِ سطلِ بالا/پایین برای سنجهٔ spread (۰..۱). */
export const SCAN_TOP_PCT = 0.8 as const
export const SCAN_BOT_PCT = 0.2 as const
