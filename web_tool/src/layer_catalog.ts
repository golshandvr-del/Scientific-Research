/** فهرستِ لایه‌های یک کارت، به همان ترتیبِ اولویتی که در CARD_LAYERS نشسته‌اند. */
export function layersForCard(cardId: string, codes: string[]): LayerInfo[] {
  return codes.map((c) => LAYER_CATALOG[`${cardId}|${c}`] || {
    code: c, name: c, verdict: '—', side: 'دوطرفه' as const,
    what: 'توضیحِ این لایه هنوز در کاتالوگ ثبت نشده است.',
  })
}
