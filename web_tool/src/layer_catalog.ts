// چرا این فایل هست (User Note: «دلم می‌خواست یه بخش info مانند داشته باشه که
// نشون بده در حال حاضر هر کارت شامل چه لایه‌هایی هست»):
//
//   سایت تا امروز فقط `sourceLayer` را نشان می‌داد — یعنی **همان یک لایه‌ای که
//   در این لحظه سیگنال داده**. لایه‌هایی که ساکتند (که در بیشترِ دقایق، یعنی
//   تقریباً همهٔ آن‌ها) در `runCard` مقدارِ null برمی‌گردانند و **دور ریخته
//   می‌شوند** (strategy_registry.ts خطِ ~۱۷۲۰). پس کاربر هیچ راهی نداشت بفهمد
//   کارتِ H8 هشت لایه دارد؛ فقط یکی را می‌دید.
//
//   این تفاوتِ معناداری در تفسیر می‌سازد: «کارتِ خنثی» وقتی یک لایه دارد یعنی
//   «تنها شاهدِ من ساکت است»، ولی وقتی هشت لایه دارد یعنی «هشت شاهدِ مستقل
//   نگاه کردند و هیچ‌کدام چیزی ندید» — و این دو، دو خبرِ کاملاً متفاوت‌اند.
//
// ⚠️ چرا کاتالوگ **توصیفی** است و از خودِ ماژول‌ها استخراج نمی‌شود:
//   کدِ لایه (`code: 'S955'`) داخلِ بدنهٔ تابعِ decide زندگی می‌کند و فقط وقتی
//   ساخته می‌شود که لایه **اجرا شود و سیگنال بدهد**. برای لایهٔ ساکت چنین
//   شیئی وجود ندارد. استخراجِ regex از سورس هم شکننده است (به قالبِ نوشتار
//   وابسته می‌شود). پس یک جدولِ صریح، و در کنارش یک **آزمونِ همگامی** که اگر
//   کسی لایه‌ای به CARD_LAYERS اضافه کرد و این‌جا را یادش رفت، قرمز شود:
//       web_tool/tools/_probe_layer_catalog.mts
//   یعنی خطرِ واگراییِ جدول با واقعیت، به‌جای «امید به یادآوری»، با آزمون مهار
//   شده است.
//
// ⚠️ این فایل **هیچ تصمیمی نمی‌گیرد**. صرفاً فراداده برای نمایش است. هیچ‌یک از
//   مقادیرِ آن به موتورِ تصمیم، سایز، یا مدیریتِ معامله نمی‌رسد ⇒ صفر ریسکِ
//   رگرسیون روی رفتارِ معاملاتیِ سایت.

export interface LayerInfo {
  /** کدِ استراتژی، همان‌که در ریپو و اسناد استفاده می‌شود. */
  code: string
  /** نامِ کوتاهِ فارسی برای نمایش در کارت. */
  name: string
  /** حکمِ رسمیِ RQS2 — عدد یا برچسب. */
  verdict: string
  /** یک جملهٔ کوتاه: این لایه دنبالِ چه رویدادی می‌گردد. */
  what: string
  /** جهتِ مجاز — کاربر باید بداند لایه یک‌طرفه است یا دوطرفه. */
  side: 'LONG' | 'SHORT' | 'دوطرفه'
}

