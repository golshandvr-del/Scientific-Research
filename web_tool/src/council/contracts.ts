/** نسخهٔ قرارداد — تغییرِ ناسازگار ⇒ v2 + adapter. */
export const COUNCIL_VERDICT_VERSION = 1 as const

/** نوعِ اجماعِ شورا. */
export type Consensus =
  | 'UNANIMOUS'   // همهٔ لایه‌های فعال هم‌جهت ⇒ اطمینانِ بالا (پیشنهادِ لاتِ ×۱.۵)
  | 'MAJORITY'    // اکثریت هم‌جهت ⇒ سیگنالِ عادی + «لایهٔ دوم هم تأیید کرد»
  | 'CONFLICT'    // یکی LONG یکی SHORT ⇒ خنثی + هشدارِ «بازارِ دوقطبی» (فیلترِ محافظ)
  | 'SINGLE'      // فقط یک لایهٔ فعال ⇒ رأیِ همان لایه (اجماع بی‌معنا)
  | 'NONE'        // هیچ لایهٔ فعالی نیست

/** رأیِ خلاصهٔ یک لایه در شورا. */
export interface LayerVote {
  code: string
  name: string
  state: 'ENTRY' | 'APPROACHING'
  direction?: 'LONG' | 'SHORT'
  probability?: number
}

/** حکمِ نسخه‌دارِ شورا (CouncilVerdict@v1). */
export interface CouncilVerdict {
  readonly v: typeof COUNCIL_VERDICT_VERSION
  readonly cardId: string
  readonly consensus: Consensus
  /** جهتِ اجماع (اگر معنا داشته باشد). */
  readonly direction?: 'LONG' | 'SHORT'
  /** ضریبِ پیشنهادیِ لات از رأیِ شورا (۱ = پایه، ۱.۵ = اجماعِ کامل، ۰ = تضاد/خنثی). */
  readonly lotMultiplier: number
  /** آیا شورا (در حالتِ فعالِ آینده) اجازهٔ ورود می‌دهد؟ در سایه‌ای فقط گزارش است. */
  readonly wouldAllowEntry: boolean
  /** شمارشِ آرا. */
  readonly longVotes: number
  readonly shortVotes: number
  readonly votes: LayerVote[]
  /** توضیحِ فارسیِ حکم (برای لاگ/گزارش، و در آینده UI: «لایهٔ دوم هم تأیید کرد»). */
  readonly note: string
}
